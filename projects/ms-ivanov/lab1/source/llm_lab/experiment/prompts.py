"""Тестовые промпты лабораторной работы.

Требование лабораторной — минимум три разнотипных промпта (генерация,
классификация, извлечение/суммаризация). Здесь их шесть: добавлены задача
на многошаговый расчёт с проверяемым числом и «ловушка» на галлюцинации.

Все промпты на русском, все требуют короткого ответа (≤ 120 слов),
но содержательно нетривиальны: в каждом есть либо жёсткий формат,
либо отвлекающая информация, либо намеренно отсутствующие данные.
"""

from __future__ import annotations

from dataclasses import dataclass

from llm_lab.evaluation.checks import (
    Check,
    ContainsAll,
    ContainsAny,
    JsonSchemaCheck,
    LabelsMatch,
    NoForeignWords,
    NotContainsAny,
    NumbersFromSource,
    NumericAnswer,
    RefusalExpected,
    RegexAbsent,
    RegexPresent,
    WordBudget,
)

SHARED_SYSTEM = (
    "Ты — ассистент бизнес-аналитика. Отвечай на русском языке, строго по формату, "
    "без вступлений и извинений. Не добавляй фактов, которых нет во входных данных."
)


@dataclass(frozen=True)
class PromptCase:
    """Один тестовый запрос."""

    id: str
    task_type: str
    title: str
    user: str
    checks: tuple[Check, ...]
    system: str | None = SHARED_SYSTEM
    reference: str = ""
    notes: str = ""

    def to_messages(self) -> list[dict[str, str]]:
        messages: list[dict[str, str]] = []
        if self.system:
            messages.append({"role": "system", "content": self.system})
        messages.append({"role": "user", "content": self.user})
        return messages



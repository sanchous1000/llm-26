# P1. Генерация делового текста с жёсткими ограничениями
# --------------------------------------------------------------------------

_P1_USER = (
    "Напиши деловое письмо-отказ подрядчику ООО «Гринтех» по договору ДГ-2024/117.\n"
    "Обязательные условия:\n"
    "1) вежливый отказ от продления договора с 1 марта 2026 года;\n"
    "2) указать причину: срыв сроков на этапе пусконаладки (2 просрочки по 11 дней);\n"
    "3) поблагодарить за работу на этапе проектирования;\n"
    "4) предложить сохранить сотрудничество по разовым заявкам;\n"
    "5) объём — не более 120 слов, без списков, обычным абзацным текстом;\n"
    "6) закончить строкой «С уважением, отдел закупок».\n"
    "Не выдумывай сумм, штрафов и фамилий."
)

P1 = PromptCase(
    id="P1",
    task_type="generation",
    title="Генерация: письмо-отказ подрядчику",
    user=_P1_USER,
    checks=(
        ContainsAll(values=("ДГ-2024/117", "Гринтех", "1 марта 2026"), name="ключевые реквизиты"),
        # «пусконалад» покрывает и «пусконаладки», и «пусконаладочном этапе».
        ContainsAny(values=("пусконалад",), name="указана причина"),
        ContainsAny(values=("разов",), name="предложение о разовых заявках"),
        RegexPresent(
            pattern=r"С уважением,\s*отдел закупок",
            name="обязательная подпись",
            description="«С уважением, отдел закупок»",
        ),
        WordBudget(max_words=140, min_words=45, name="лимит 120 слов (+20 допуск)"),
        NotContainsAny(
            values=("штраф", "неустойк", "пени", "рублей", "Иванов", "Петров"),
            name="нет выдуманных сумм и фамилий",
            weight=1.5,
        ),
        # Числа только из условия: «в общей сложности 21 день» — выдуманная (и неверная) сумма.
        NumbersFromSource(source=_P1_USER, name="числа только из условия", weight=1.5),
        NoForeignWords(name="только русский язык"),
    ),
    reference="Абзацный текст 90–120 слов с реквизитами договора и подписью.",
    notes="Проверяет следование множественным ограничениям и удержание от додумывания.",
)



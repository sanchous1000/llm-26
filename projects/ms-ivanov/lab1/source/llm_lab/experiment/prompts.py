ALL_PROMPTS: tuple[PromptCase, ...] = (P1, P2, P3, P4, P5, P6)

# Минимальный набор по условию лабораторной: генерация / классификация / извлечение.
REQUIRED_PROMPT_IDS: tuple[str, ...] = ("P1", "P2", "P3")


def resolve_prompts(prompt_ids: tuple[str, ...]) -> tuple[PromptCase, ...]:
    """Отбор промптов по идентификаторам (пустой кортеж = все)."""
    if not prompt_ids:
        return ALL_PROMPTS
    index = {case.id.upper(): case for case in ALL_PROMPTS}
    selected: list[PromptCase] = []
    for raw in prompt_ids:
        key = raw.strip().upper()
        if key not in index:
            known = ", ".join(index)
            raise ValueError(f"Неизвестный промпт {raw!r}. Доступны: {known}")
        selected.append(index[key])
    return tuple(selected)

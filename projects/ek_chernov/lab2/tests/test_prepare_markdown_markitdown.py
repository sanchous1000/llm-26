"""Проверяет нормализацию Markdown, извлечённого через MarkItDown."""

from source.scripts.prepare_markdown_markitdown import normalize_page


def test_normalize_recipe_page() -> None:
    """
    Проверяет разметку заголовков, ингредиентов и шагов рецепта.

    Parameters:
        Не предусмотрены.

    Returns:
        None: Проверка завершается утверждением pytest.

    Fallbacks:
        Не предусмотрены.
    """
    markdown = normalize_page(
        3,
        [
            " К ",
            "УРИЦА",
            "Курица с овощами",
            "Ингредиенты",
            "Для блюда:",
            "● Куриное филе",
            "500 г",
            "● Томаты",
            "Способ приготовления",
            "1) Нарезать филе.",
            "Добавить овощи.",
            "2. Запечь.",
        ],
    )

    assert markdown == (
        "<!-- page: 3 -->\n\n"
        "3\n\n"
        "# КУРИЦА\n\n"
        "## Курица с овощами\n\n"
        "### ингредиенты\n\n"
        "Для блюда:\n\n"
        "- Куриное филе 500 г\n"
        "- Томаты\n\n"
        "### Способ приготовления\n\n"
        "1. Нарезать филе. Добавить овощи.\n"
        "2. Запечь."
    )
